# Scratch-repository tests for check-generated-stamps.ps1 (T-GENERATED-STAMP-REFUSES-DIRTY-TREES,
# plan row 99): four stamps naming a clean ancestor pass, and so does a stamp naming HEAD itself;
# the dirty suffix, a sha that names no commit, a commit that is not an ancestor of HEAD, a line
# that is not the grammar, a file with no stamp, a file with two, a missing file and four files
# naming two commits are each refused for their own reason; and a shallow clone in which the sha
# does not resolve exits 2, not 0.

$ErrorActionPreference = "Stop"
if (Get-Variable -Name PSNativeCommandUseErrorActionPreference -Scope Global -ErrorAction SilentlyContinue) {
    $PSNativeCommandUseErrorActionPreference = $false
}

$gate = Join-Path $PSScriptRoot "check-generated-stamps.ps1"
$root = Join-Path ([IO.Path]::GetTempPath()) ("folio-generated-stamps-gate-" + [guid]::NewGuid())
$directory = "docs/plans/design/runtime-dep-map"
$names = @("fields.tsv", "topics.tsv", "doors.tsv", "unclassified.tsv")
$header = "# Generated by the fixture; do not`n# edit.`n"
$body = "a`tb`n1`t2`n"

function Write-Map([string]$Repo, [string]$Stamp, [string]$Only = "", [string]$OnlyStamp = $null) {
    foreach ($name in $names) {
        $path = Join-Path $Repo "$directory/$name"
        [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($path)) | Out-Null
        $line = if ($name -eq $Only -and $null -ne $OnlyStamp) { $OnlyStamp } else { $Stamp }
        $text = if ($line.Length -eq 0) { $header + $body } else { $header + $line + "`n" + $body }
        [IO.File]::WriteAllText($path, $text)
    }
}

function Run-Gate([string]$Repo, [int]$Want, [string]$Case) {
    $output = & pwsh -NoProfile -File $gate -Repo $Repo 2>&1 | Out-String
    $got = $LASTEXITCODE
    if ($got -ne $Want) { throw "$Case returned $got, wanted $Want`n$output" }
    return $output
}

function Passes([string]$Case) {
    $output = Run-Gate $root 0 $Case
    if ($output -notmatch "a clean ancestor of HEAD") { throw "$Case passed without saying so: $output" }
}

function Refused([string]$Case, [string]$Reason, [string]$Repo = $root) {
    $output = Run-Gate $Repo 1 $Case
    if ($output -notmatch [regex]::Escape($Reason)) {
        throw "$Case was refused for the wrong reason (wanted '$Reason'): $output"
    }
}

function Short([string]$Rev) { return ((& git rev-parse --short=8 $Rev) | Out-String).Trim() }

try {
    [IO.Directory]::CreateDirectory($root) | Out-Null
    Push-Location $root
    try {
        & git init -q -b main
        & git config user.email generated-stamps-gate@example.invalid
        & git config user.name generated-stamps-gate
        & git config core.autocrlf false
        [IO.File]::WriteAllText((Join-Path $root "code.rs"), "fn a() {}`n")
        & git add .
        & git commit -q -m "the code"
        $code = Short HEAD

        # A sibling branch's commit: a real commit, never an ancestor of main.
        & git checkout -q -b sibling
        [IO.File]::WriteAllText((Join-Path $root "code.rs"), "fn b() {}`n")
        & git commit -q -am "elsewhere"
        $foreign = Short HEAD
        & git checkout -q main

        # The map measured at the code commit, committed on top of it.
        Write-Map $root "# measured at $code"
        & git add .
        & git commit -q -m "generated: the map"
        Passes "a clean ancestor"

        # A stamp naming HEAD itself (a commit is its own ancestor), with a longer sha.
        $head = ((& git rev-parse --short=12 HEAD) | Out-String).Trim()
        Write-Map $root "# measured at $head"
        Passes "the stamp names HEAD"

        Write-Map $root "# measured at $code with uncommitted changes"
        Refused "the dirty suffix" "measured on a tree with uncommitted changes"

        Write-Map $root "# measured at deadbeef0"
        Refused "a sha that names no commit" "deadbeef0 names no commit of this repository"

        Write-Map $root "# measured at $foreign"
        Refused "a commit that is not an ancestor" "$foreign is not an ancestor of HEAD"

        Write-Map $root "# measured at xyz"
        Refused "a malformed line" "is not '# measured at <8-40 hex>[ with uncommitted changes]'"

        Write-Map $root "# measured at $code, clean"
        Refused "a suffix that is not the grammar's" "is not '# measured at <8-40 hex>"

        Write-Map $root "# measured at $code" "doors.tsv" ""
        Refused "a file with no stamp" "doors.tsv: no '# measured at' line"

        Write-Map $root "# measured at $code" "topics.tsv" "# measured at $code`n# measured at $code"
        Refused "a file with two stamps" "topics.tsv: 2 '# measured at' lines"

        Write-Map $root "# measured at $code" "fields.tsv" "# measured at $head"
        Refused "two commits across the four" "the four files name 2 commits"

        Write-Map $root "# measured at $code"
        Remove-Item -LiteralPath (Join-Path $root "$directory/unclassified.tsv")
        Refused "a missing file" "unclassified.tsv: the file is missing"
        & git checkout -q -- .
        Passes "restored"

        # A shallow clone of depth one: the code commit is not in it, and that is no pass.
        $shallow = "$root-shallow"
        & git clone -q --depth 1 "file:///$($root -replace '\\', '/')" $shallow 2>&1 | Out-Null
        try {
            $output = Run-Gate $shallow 2 "a shallow clone"
            if ($output -notmatch "This is not a pass") { throw "the shallow clone did not say it was no pass: $output" }
        } finally {
            if (Test-Path -LiteralPath $shallow) { Remove-Item -LiteralPath $shallow -Recurse -Force }
        }
    } finally {
        Pop-Location
    }
} finally {
    if (Test-Path -LiteralPath $root) { Remove-Item -LiteralPath $root -Recurse -Force }
}

Write-Host "check-generated-stamps: clean ancestor, HEAD itself, dirty, unknown sha, foreign sha, malformed, bad suffix, no stamp, two stamps, two commits, missing file and shallow-clone cases pass"
exit 0
