/// RED (A1a, budget note R7) — **`docs/ARCHITECTURE.md` §5.3's table is the registry.**
///
/// The table is rendered from `window_waits.tsv` and compared with the one between the markers;
/// the rendering is left in `target/window-waits-table.md`, which
/// `scripts/dev/generate-window-waits-table.ps1` copies into the document. One list, so the prose
/// and the registry cannot disagree while every check passes.
///
/// MUTATION: edit a status in the registry and not the document (or the reverse) and it goes red.
#[test]
fn the_architecture_table_is_the_registry() {
    let root = repository_root();
    let wanted = rendered();
    let generated = root.join("target").join("window-waits-table.md");
    if let Some(parent) = generated.parent() {
        std::fs::create_dir_all(parent).expect("the workspace has a target directory");
    }
    std::fs::write(&generated, wanted.as_bytes()).expect("target/ is writable");
    let document = std::fs::read_to_string(root.join("docs").join("ARCHITECTURE.md"))
        .expect("docs/ARCHITECTURE.md is checked in")
        .replace("\r\n", "\n");
    let begin = document
        .find(BEGIN)
        .expect("ARCHITECTURE §5.3 has the generated table's opening marker")
        + BEGIN.len();
    let end = begin
        + document[begin..]
            .find(END)
            .expect("and its closing marker, after it");
    let held = &document[begin..end];
    if let Some((number, held_line, wanted_line)) = held
        .lines()
        .map(Some)
        .chain(std::iter::repeat(None))
        .zip(wanted.lines().map(Some).chain(std::iter::repeat(None)))
        .take(held.lines().count().max(wanted.lines().count()))
        .enumerate()
        .find(|(_, (held_line, wanted_line))| held_line != wanted_line)
        .map(|(index, (held_line, wanted_line))| {
            (
                index + 1,
                held_line.unwrap_or("<end of the table>"),
                wanted_line.unwrap_or("<end of the table>"),
            )
        })
    {
        panic!(
            "ARCHITECTURE §5.3's table, line {number}, is not what window_waits.tsv says — \
             run scripts/dev/generate-window-waits-table.ps1\n  \
             the document: {held_line}\n  the registry: {wanted_line}"
        );
    }
    assert_eq!(held, wanted, "the table ends where the registry does");
}

