/// Tokens that, written before `Name {`, make it a declaration or a type rather than a literal.
const NOT_A_LITERAL: [&str; 9] = [
    "struct", "enum", "union", "impl", "for", "trait", "->", "type", "dyn",
];

/// Every struct literal of `name` in a package's product code: `Name {`, and `Self {` inside the
/// type's own `impl` blocks — every spelling (Codex P8).
fn literals_of(src: &Src, name: &str) -> Vec<usize> {
    let is_literal = |at: usize| {
        let after = src.lex(at, (at + 64).min(src.file_end(at)));
        let file_start = src.index.file_at(at).map_or(0, |f| f.span().start());
        let before = src.lex(at.saturating_sub(64).max(file_start), at);
        src.is(after.get(1), "{")
            && !before
                .last()
                .is_some_and(|t| NOT_A_LITERAL.contains(&src.text(*t)))
    };
    let blocks: Vec<_> = src
        .index
        .impls()
        .iter()
        .filter(|block| block.type_owner() == name)
        .map(bt_source::ImplRecord::body)
        .collect();
    src.named(name)
        .into_iter()
        .chain(
            src.named("Self")
                .into_iter()
                .filter(|at| blocks.iter().any(|body| body.holds(*at))),
        )
        .filter(|at| is_literal(*at) && src.in_product(*at))
        .collect()
}

/// **A worker's capability has one constructor and no trait road to another**: one `WorkerCtx`
/// struct literal in the product, in `admission::lend_worker` (A1b), called by the thread door
/// and by `enter_standalone_main` once each; `WorkerCtx` and `WaitToken` each have one `impl`
/// block, the inherent one, and derive nothing.
///
/// **And the two mints are fenced** (A2a, revision (j)11.1), because an entrance that takes a
/// capability may leave the vocabulary only while nothing else can make one: `WaitToken`'s one
/// struct literal is `WaitToken::fresh`'s, and `fresh` is named in the product exactly where
/// `admission::admitted` calls it (twice: the unmetered and the metered road); `lend_worker` is
/// named exactly by its two owners. Every **reference** is counted — a name handed on as a
/// function value (`.map(WaitToken::fresh)`, `run(lend_worker)`) is one — by the identifier view,
/// never by the spelling `name(`. `fresh` and every field of both capabilities are private: that
/// pinned visibility is what keeps every reference to them inside `bt-effects`' `crate::admission`,
/// where this counts them. `lend_worker` is the one public mint, for the thread door, which is
/// `bt-platform`'s because it sets the platform's scheduling band (CC-3): its references are counted
/// in every package of the product, so a third caller anywhere is a failure here.
///
/// What stays outside, as revision (b)2 names it and (j)11.1 restates: an inference-typed
/// fabrication inside `bt-platform`'s own `unsafe` (a `transmute` whose target type is fixed at a
/// door's parameter rather than written) is not an accident this guard is built to catch.
fn a_capability_has_one_constructor_and_no_trait_road(world: &World) -> Vec<String> {
    let mut failures = Vec::new();
    let literals: Vec<String> = world
        .srcs
        .iter()
        .flat_map(|src| {
            literals_of(src, "WorkerCtx")
                .into_iter()
                .map(|at| src.owner_of(at))
        })
        .collect();
    if literals != ["bt-effects crate::admission::lend_worker"] {
        failures.push(format!(
            "`WorkerCtx` is built by a struct literal in one place, `admission::lend_worker`; \
             found {literals:?}"
        ));
    }
    let token_literals: Vec<String> = world
        .srcs
        .iter()
        .flat_map(|src| {
            literals_of(src, "WaitToken")
                .into_iter()
                .map(|at| src.owner_of(at))
        })
        .collect();
    if token_literals != ["bt-effects crate::admission::WaitToken::fresh"] {
        failures.push(format!(
            "`WaitToken` is built by a struct literal in one place, `WaitToken::fresh`; found \
             {token_literals:?}"
        ));
    }
    let admission = admission_module(world.src("bt-effects"));
    // Every reference in the product, its declaration excluded: a call, a value, a path to it.
    let references = |name: &str, within: Option<bt_source::Span>| {
        let mut found = BTreeMap::new();
        for src in &world.srcs {
            for at in src.named(name) {
                let file_start = src.index.file_at(at).map_or(0, |f| f.span().start());
                let before = src.lex(at.saturating_sub(8).max(file_start), at);
                let outside =
                    within.is_some_and(|span| src.package != "bt-effects" || !span.holds(at));
                if src.is(before.last(), "fn") || outside || !src.in_product(at) {
                    continue;
                }
                *found.entry(src.owner_of(at)).or_insert(0) += 1;
            }
        }
        found
    };
    let fresh = references("fresh", admission);
    let wanted_fresh = BTreeMap::from([("bt-effects crate::admission::admitted".to_owned(), 2)]);
    if fresh != wanted_fresh {
        failures.push(format!(
            "`WaitToken::fresh` is named only by `admission::admitted`, twice — a call or a value \
             is a reference, and any other is a second mint that skips the role, the phase and \
             the meter; found {fresh:?}"
        ));
    }
    let callers = references("lend_worker", None);
    let wanted = BTreeMap::from([
        (
            "bt-effects crate::admission::enter_standalone_main".to_owned(),
            1,
        ),
        (
            "bt-platform crate::admission::spawn_at_priority_with_stack".to_owned(),
            1,
        ),
    ]);
    if callers != wanted {
        failures.push(format!(
            "`lend_worker` is named by the thread door and by `enter_standalone_main`, once \
             each (a call or a value is a reference); found {callers:?}"
        ));
    }
    let effects = world.src("bt-effects");
    for (query, what) in [
        (
            ItemQuery::method("WaitToken", "fresh"),
            "`WaitToken::fresh`",
        ),
        (
            ItemQuery::field("WaitToken", "_scope"),
            "`WaitToken`'s `_scope`",
        ),
        (
            ItemQuery::field("WaitToken", "_door"),
            "`WaitToken`'s `_door`",
        ),
        (
            ItemQuery::field("WaitToken", "_local"),
            "`WaitToken`'s `_local`",
        ),
        (
            ItemQuery::field("WorkerCtx", "name"),
            "`WorkerCtx`'s `name`",
        ),
        (
            ItemQuery::field("WorkerCtx", "_local"),
            "`WorkerCtx`'s `_local`",
        ),
    ] {
        match effects.index.find(&query.in_module("crate::admission")) {
            Ok(records) => {
                for record in records {
                    let declaration =
                        effects.lex(record.declaration().start(), record.declaration().end());
                    if declaration.iter().any(|t| effects.text(*t) == "pub") {
                        failures.push(format!(
                            "{what} is visible outside `crate::admission` at {}: a mint, and a \
                             field a literal elsewhere could fill, stay private",
                            effects.location(record.whole().start())
                        ));
                    }
                }
            }
            Err(failure) => failures.push(format!("{what}: {failure}")),
        }
    }
    for type_name in ["WorkerCtx", "WaitToken"] {
        let blocks: Vec<String> = world
            .srcs
            .iter()
            .flat_map(|src| {
                src.index
                    .impls()
                    .iter()
                    .filter(|block| {
                        block.type_owner() == type_name && src.in_product(block.whole().start())
                    })
                    .map(|block| match block.trait_name() {
                        Some(name) => format!("impl {name} for {type_name}"),
                        None => format!("impl {type_name}"),
                    })
            })
            .collect();
        if blocks != [format!("impl {type_name}")] {
            failures.push(format!(
                "`{type_name}` has one `impl` block, its inherent one — no `Default`, `Clone`, \
                 `Copy`, `From`, `Send` or `Sync` road to another; found {blocks:?}"
            ));
        }
        match effects
            .index
            .find(&ItemQuery::type_item(type_name).in_module("crate::admission"))
        {
            Ok(records) => {
                for record in records {
                    let declaration =
                        effects.lex(record.declaration().start(), record.declaration().end());
                    if declaration.iter().any(|t| effects.text(*t) == "derive") {
                        failures.push(format!(
                            "`{type_name}` derives a trait at {}: a derived `Clone`, `Copy` or \
                             `Default` is a second constructor",
                            effects.location(record.whole().start())
                        ));
                    }
                }
            }
            Err(failure) => failures.push(format!("`crate::admission::{type_name}`: {failure}")),
        }
    }
    failures
}

