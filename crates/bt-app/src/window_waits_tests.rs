// ── the lexer: code tokens, comments skipped, a literal one token ───────────────────────────

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    Ident,
    Punct,
    Literal,
    Lifetime,
}

/// One code token, by its offsets in the index's union.
#[derive(Clone, Copy, Debug)]
struct Tok {
    kind: Kind,
    start: usize,
    end: usize,
}

/// One product package's index.
struct Src {
    package: &'static str,
    index: &'static Index,
    /// The features a product build turns on in this package ([`Product::features`]).
    features: &'static BTreeSet<String>,
}

/// The punctuation read as one token.
const JOINED: [&str; 12] = [
    "...", "..=", "::", "->", "=>", "..", "==", "!=", "<=", ">=", "&&", "||",
];

impl Src {
    fn text(&self, tok: Tok) -> &'static str {
        &self.index.union()[tok.start..tok.end]
    }

    /// Whether `tok` is code spelled `spelled`.
    fn is(&self, tok: Option<&Tok>, spelled: &str) -> bool {
        tok.is_some_and(|tok| tok.kind != Kind::Literal && self.text(*tok) == spelled)
    }

    fn file_end(&self, at: usize) -> usize {
        self.index
            .file_at(at)
            .map_or(self.index.union().len(), |file| file.span().end())
    }

    /// The code tokens of `[from, to)`: comments are skipped (they are the index's own masks), a
    /// literal is one token, and a name, a lifetime and the joined punctuation are one each.
    fn lex(&self, from: usize, to: usize) -> Vec<Tok> {
        let text = self.index.union();
        let bytes = text.as_bytes();
        let comments = self.index.comments();
        let literals = self.index.literals();
        let mut comment = comments.partition_point(|c| c.span().end() <= from);
        let mut literal = literals.partition_point(|l| l.span().end() <= from);
        let starts = |b: u8| b.is_ascii_alphabetic() || b == b'_' || b >= 0x80;
        let continues = |b: u8| b.is_ascii_alphanumeric() || b == b'_' || b >= 0x80;
        let word_end = |from: usize| {
            let mut end = from;
            while end < to && continues(bytes[end]) {
                end += 1;
            }
            end
        };
        let mut out = Vec::new();
        let mut at = from;
        while at < to {
            while comment < comments.len() && comments[comment].span().end() <= at {
                comment += 1;
            }
            if comment < comments.len() && comments[comment].span().start() <= at {
                at = comments[comment].span().end();
                continue;
            }
            while literal < literals.len() && literals[literal].span().end() <= at {
                literal += 1;
            }
            if literal < literals.len() && literals[literal].span().start() <= at {
                let span = literals[literal].span();
                out.push(Tok {
                    kind: Kind::Literal,
                    start: span.start(),
                    end: span.end(),
                });
                at = span.end();
                continue;
            }
            let byte = bytes[at];
            let (kind, start, end) = if byte.is_ascii_whitespace() {
                at += 1;
                continue;
            } else if byte == b'r'
                && bytes.get(at + 1) == Some(&b'#')
                && bytes.get(at + 2).is_some_and(|b| starts(*b))
            {
                (Kind::Ident, at + 2, word_end(at + 2))
            } else if starts(byte) {
                (Kind::Ident, at, word_end(at))
            } else if byte == b'\'' && bytes.get(at + 1).is_some_and(|b| starts(*b)) {
                (Kind::Lifetime, at + 1, word_end(at + 1))
            } else {
                let rest = &bytes[at..to];
                let width = JOINED
                    .iter()
                    .find(|joined| rest.starts_with(joined.as_bytes()))
                    .map_or_else(
                        || text[at..].chars().next().map_or(1, char::len_utf8),
                        |joined| joined.len(),
                    );
                (Kind::Punct, at, at + width)
            };
            out.push(Tok { kind, start, end });
            at = end;
        }
        out
    }

    /// The tokens of the bracketed group opening at `open`, delimiters included.
    fn group(&self, open: usize) -> Vec<Tok> {
        let end = self.file_end(open);
        let mut window = 4096;
        loop {
            let to = (open + window).min(end);
            let toks = self.lex(open, to);
            if let Some(close) = closing(self, &toks, 0) {
                return toks[..=close].to_vec();
            }
            if to == end {
                return toks;
            }
            window *= 4;
        }
    }

    /// Whether a file belongs to a product target: a library, or `bt-app`'s `folio` binary.
    fn product_file(&self, file: &FileRecord) -> bool {
        file.owners().iter().any(|owner| {
            owner.compilation.permits_product()
                && owner
                    .steps
                    .iter()
                    .all(|step| product_build_permits(&step.predicates, self.features))
                && match owner.target.kind {
                    TargetKind::Library => true,
                    TargetKind::Binary => self.package == "bt-app" && owner.target.name == "folio",
                    TargetKind::IntegrationTest
                    | TargetKind::Example
                    | TargetKind::Bench
                    | TargetKind::BuildScript => false,
                }
        })
    }

    /// Whether an item record is product code.
    fn product_item(&self, record: &ItemRecord) -> bool {
        self.product_file(self.index.file_of(record))
            && record.identities().any(|identity| {
                identity.variant.permits_product()
                    && product_build_permits(identity.variant.predicates(), self.features)
            })
    }

    /// Whether a build of the shipped program contains the token at `at`.
    fn in_product(&self, at: usize) -> bool {
        let Some(file) = self.index.file_at(at) else {
            return false;
        };
        if !self.product_file(file) {
            return false;
        }
        let tokens = self.index.tokens();
        let literals = self.index.literals();
        let token = tokens
            .get(tokens.partition_point(|t| t.span().end() <= at))
            .map(|t| t.span());
        let literal = literals
            .get(literals.partition_point(|l| l.span().end() <= at))
            .map(|l| l.span());
        let span = [token, literal]
            .into_iter()
            .flatten()
            .find(|span| span.holds(at) || span.start() >= at)
            .filter(|span| span.within(file.span()))
            .unwrap_or_else(|| file.span());
        Occurrence {
            span,
            certainty: Certainty::Resolved,
        }
        .in_the_product(self.index)
    }

    /// The smallest callable holding `at`.
    fn callable_at(&self, at: usize) -> Option<&'static ItemRecord> {
        self.index
            .items()
            .iter()
            .filter(|record| record.kind().is_callable() && record.whole().holds(at))
            .min_by_key(|record| record.whole().len())
    }

    /// The smallest module holding `at`, by its first path.
    fn module_at(&self, at: usize) -> &'static str {
        self.index
            .modules()
            .iter()
            .filter(|module| module.span().holds(at))
            .min_by_key(|module| module.span().len())
            .map_or("crate", |module| module.module_paths()[0].as_str())
    }

    /// Who owns the code at `at`: `bt-platform crate::macos_app::delegate_answers_the_dock_menu`,
    /// or the module when no function holds it (the inside of `define_class!`).
    fn owner_of(&self, at: usize) -> String {
        match self.callable_at(at) {
            Some(record) => format!("{} {}", self.package, name_of(record)),
            None => format!("{} {}", self.package, self.module_at(at)),
        }
    }

    fn location(&self, at: usize) -> String {
        self.index.locate(at).map_or_else(
            || format!("{} at byte {at}", self.package),
            |l| format!("{}:{}", l.file.display(), l.line),
        )
    }

    /// Every token spelled `name`, by its offset.
    fn named(&self, name: &str) -> Vec<usize> {
        self.index
            .tokens()
            .iter()
            .filter(|token| self.index.text(token.name_span()) == name)
            .map(|token| token.name_span().start())
            .collect()
    }

    /// The names spelled in `[from, to)`, out of `names`.
    fn names_in(&self, from: usize, to: usize, names: &[&str]) -> Vec<(usize, &'static str)> {
        let tokens = self.index.tokens();
        let first = tokens.partition_point(|t| t.span().start() < from);
        tokens[first..]
            .iter()
            .take_while(|t| t.span().start() < to)
            .map(|t| (t.name_span().start(), self.index.text(t.name_span())))
            .filter(|(_, name)| names.contains(name))
            .collect()
    }
}

/// The packages among `dependencies` that `src` re-exports to its own dependents: a product
/// `pub use dependency::…` (`pub use bt_effects::admission::*;`, `pub use bt_effects::file_reads;`),
/// the dependency named by its crate name. A `pub(crate) use` or a private `use` lends a dependent
/// nothing, and neither does a `use` in test code.
fn re_exported_by(src: &Src, dependencies: &BTreeSet<usize>, srcs: &[Src]) -> BTreeSet<usize> {
    dependencies
        .iter()
        .copied()
        .filter(|&dependency| {
            let crate_name = srcs[dependency].package.replace('-', "_");
            src.named(&crate_name).into_iter().any(|at| {
                let file_start = src.index.file_at(at).map_or(0, |f| f.span().start());
                let before = src.lex(at.saturating_sub(32).max(file_start), at);
                before.len() >= 2
                    && src.is(before.get(before.len() - 2), "pub")
                    && src.is(before.last(), "use")
                    && src.in_product(at)
            })
        })
        .collect()
}

/// `crate::x::Type::name`, by the item's first module path, without its arm.
fn name_of(record: &ItemRecord) -> String {
    let module = record.module_paths()[0];
    match record.type_owner() {
        Some(owner) => format!("{module}::{owner}::{}", record.name()),
        None => format!("{module}::{}", record.name()),
    }
}

/// `bt-pty crate::<PtySession as Drop>::drop`, with each predicate of the arm the item stands on
/// in brackets — `[windows]`, `[target_os = "macos"]` — when it has one: the key the tables below
/// name a body by.
fn key_of(src: &Src, record: &ItemRecord) -> String {
    let identity = record
        .identities()
        .next()
        .expect("an item is reached by a declaration");
    let mut key = format!("{} {}::", src.package, identity.module_path);
    match (&identity.type_owner, &identity.trait_name) {
        (Some(owner), Some(trait_name)) => key.push_str(&format!("<{owner} as {trait_name}>::")),
        (Some(owner), None) => key.push_str(&format!("{owner}::")),
        (None, Some(trait_name)) => key.push_str(&format!("{trait_name}::")),
        (None, None) => {}
    }
    key.push_str(&identity.name);
    for predicate in identity.variant.predicates() {
        key.push_str(&format!(" [{predicate}]"));
    }
    key
}

/// The index of the token closing the group `toks[open]` opens.
fn closing(src: &Src, toks: &[Tok], open: usize) -> Option<usize> {
    let mut depth = 0usize;
    for (at, tok) in toks.iter().enumerate().skip(open) {
        if tok.kind != Kind::Punct {
            continue;
        }
        match src.text(*tok) {
            "(" | "[" | "{" => depth += 1,
            ")" | "]" | "}" => {
                depth = depth.checked_sub(1)?;
                if depth == 0 {
                    return Some(at);
                }
            }
            _ => {}
        }
    }
    None
}

/// `a, b(c, d), e = "f"` split at its top-level commas.
fn split_commas(src: &Src, toks: &[Tok]) -> Vec<Vec<Tok>> {
    let mut parts = vec![Vec::new()];
    let mut depth = 0usize;
    for tok in toks {
        if tok.kind == Kind::Punct {
            match src.text(*tok) {
                "(" | "[" | "{" | "<" => depth += 1,
                ")" | "]" | "}" | ">" => depth = depth.saturating_sub(1),
                "," if depth == 0 => {
                    parts.push(Vec::new());
                    continue;
                }
                _ => {}
            }
        }
        if let Some(part) = parts.last_mut() {
            part.push(*tok);
        }
    }
    parts.retain(|part| !part.is_empty());
    parts
}

// ── attributes ─────────────────────────────────────────────────────────────────────────────

/// One attribute: `#[…]` or `#![…]`, and the tokens between its brackets.
struct Attribute {
    inner: bool,
    start: usize,
    body: Vec<Tok>,
}

/// Every attribute written in a package, product or not: a `#` in code followed by `[` or `![`.
fn attributes(src: &Src) -> Vec<Attribute> {
    let text = src.index.union();
    let bytes = text.as_bytes();
    let comments = src.index.comments();
    let literals = src.index.literals();
    let masked = |at: usize| {
        let comment = comments.partition_point(|c| c.span().end() <= at);
        let literal = literals.partition_point(|l| l.span().end() <= at);
        comments.get(comment).is_some_and(|c| c.span().holds(at))
            || literals.get(literal).is_some_and(|l| l.span().holds(at))
    };
    let skip_space = |mut at: usize| {
        while at < bytes.len() && bytes[at].is_ascii_whitespace() {
            at += 1;
        }
        at
    };
    let mut out = Vec::new();
    for (at, _) in text.match_indices('#') {
        let mut next = skip_space(at + 1);
        let inner = bytes.get(next) == Some(&b'!');
        if inner {
            next = skip_space(next + 1);
        }
        if bytes.get(next) != Some(&b'[') || masked(at) {
            continue;
        }
        let group = src.group(next);
        if group.len() >= 2 {
            out.push(Attribute {
                inner,
                start: at,
                body: group[1..group.len() - 1].to_vec(),
            });
        }
    }
    out
}

/// A path written as tokens, spaces dropped (`clippy :: style` is `clippy::style`), and how many
/// tokens it took.
fn path_of(src: &Src, toks: &[Tok]) -> (String, usize) {
    let mut path = String::new();
    let mut used = 0;
    for tok in toks {
        match tok.kind {
            Kind::Ident => path.push_str(src.text(*tok)),
            Kind::Punct if src.text(*tok) == "::" => path.push_str("::"),
            _ => break,
        }
        used += 1;
    }
    (path, used)
}

/// Every `allow`/`expect` an attribute says, however deep inside `cfg_attr`: (verb, lint).
fn suppressions(src: &Src, toks: &[Tok]) -> Vec<(String, String)> {
    let (path, used) = path_of(src, toks);
    let rest = &toks[used..];
    let args = match rest.first() {
        Some(open) if src.is(Some(open), "(") => &rest[1..rest.len().saturating_sub(1)],
        _ => return Vec::new(),
    };
    match path.as_str() {
        "allow" | "expect" => split_commas(src, args)
            .into_iter()
            .filter_map(|lint| {
                let (name, used) = path_of(src, &lint);
                (used == lint.len() && !name.is_empty()).then(|| (path.clone(), name))
            })
            .collect(),
        "cfg_attr" => split_commas(src, args)
            .into_iter()
            .skip(1)
            .flat_map(|attribute| suppressions(src, &attribute))
            .collect(),
        _ => Vec::new(),
    }
}

// ── the world: the product's callables and fields, and calls resolved to them ───────────────

/// A first-party function or method, or a `From::from` that `#[from]` generates.
#[derive(Clone, Debug)]
struct Callable {
    src: usize,
    module: String,
    type_owner: Option<String>,
    trait_name: Option<String>,
    /// `None` for a generated `From::from`, which no byte holds.
    record: Option<&'static ItemRecord>,
}

struct World {
    srcs: Vec<Src>,
    /// What each package's product code can name: itself, its direct first-party product
    /// dependencies ([`Product::packages`]) — a dev-dependency or a test-only optional one is not
    /// one — and every package one of those re-exports ([`re_exported_by`]): `bt-app` names
    /// `bt-effects`' admission through `bt_platform::admission`.
    reach: Vec<BTreeSet<usize>>,
    callables: HashMap<String, Vec<Callable>>,
    fields: HashMap<(String, String), Vec<(usize, &'static ItemRecord)>>,
    deref_types: BTreeSet<String>,
}

/// Words that open a parenthesis without calling anything.
const KEYWORDS: [&str; 22] = [
    "if", "while", "match", "return", "in", "as", "for", "loop", "move", "else", "let", "mut",
    "ref", "unsafe", "async", "await", "where", "impl", "dyn", "fn", "break", "continue",
];

impl World {
    fn new() -> Self {
        Self::of(product())
    }

    /// The world of `product`'s packages, each reaching itself and its product dependencies.
    fn of(product: Product) -> Self {
        let Product {
            packages,
            mut features,
        } = product;
        let srcs: Vec<Src> = packages
            .iter()
            .map(|(name, _)| {
                let package: &'static str = Box::leak(name.clone().into_boxed_str());
                Src {
                    package,
                    index: Index::of_package(package),
                    features: Box::leak(Box::new(features.remove(name).unwrap_or_default())),
                }
            })
            .collect();
        let direct: Vec<BTreeSet<usize>> = packages
            .iter()
            .map(|(_, dependencies)| {
                dependencies
                    .iter()
                    .map(|name| {
                        srcs.iter()
                            .position(|src| src.package == name)
                            .expect("a product package's dependency is a product package")
                    })
                    .collect()
            })
            .collect();
        let re_exports: Vec<BTreeSet<usize>> = srcs
            .iter()
            .enumerate()
            .map(|(at, src)| re_exported_by(src, &direct[at], &srcs))
            .collect();
        let reach = (0..srcs.len())
            .map(|at| {
                let mut reach = direct[at].clone();
                reach.insert(at);
                // A re-export of a re-export is a name too: grow to a fixed point.
                loop {
                    let more: BTreeSet<usize> = reach
                        .iter()
                        .filter(|&&other| other != at)
                        .flat_map(|&other| re_exports[other].iter().copied())
                        .filter(|package| !reach.contains(package))
                        .collect();
                    if more.is_empty() {
                        break reach;
                    }
                    reach.extend(more);
                }
            })
            .collect();
        let mut callables: HashMap<String, Vec<Callable>> = HashMap::new();
        let mut fields: HashMap<(String, String), Vec<(usize, &'static ItemRecord)>> =
            HashMap::new();
        let mut deref_types = BTreeSet::new();
        for (at, src) in srcs.iter().enumerate() {
            for block in src.index.impls() {
                if src.in_product(block.whole().start())
                    && block.trait_name().is_some_and(|name| {
                        name.rsplit("::")
                            .next()
                            .is_some_and(|last| last.trim() == "Deref")
                    })
                {
                    deref_types.insert(block.type_owner().to_owned());
                }
            }
            for record in src.index.items() {
                if record.kind() == ItemKind::Field
                    && let Some(owner) = record.type_owner()
                    && (src.product_item(record) || owner == "ReceiverTypingSourceShapes")
                {
                    fields
                        .entry((owner.to_owned(), record.name().to_owned()))
                        .or_default()
                        .push((at, record));
                }
                if !src.product_item(record) {
                    continue;
                }
                if record.kind().is_callable() {
                    callables
                        .entry(record.name().to_owned())
                        .or_default()
                        .push(Callable {
                            src: at,
                            module: record.module_paths()[0].to_owned(),
                            type_owner: record.type_owner().map(ToOwned::to_owned),
                            trait_name: record.trait_name().map(ToOwned::to_owned),
                            record: Some(record),
                        });
                }
            }
            // `#[from]` on an error enum's field makes a first-party `From::from` no byte holds.
            for attribute in attributes(src) {
                if path_of(src, &attribute.body).0 != "from" || !src.in_product(attribute.start) {
                    continue;
                }
                if let Some(owner) = src
                    .index
                    .items()
                    .iter()
                    .filter(|r| r.kind() == ItemKind::Enum && r.whole().holds(attribute.start))
                    .min_by_key(|r| r.whole().len())
                {
                    callables
                        .entry("from".to_owned())
                        .or_default()
                        .push(Callable {
                            src: at,
                            module: owner.module_paths()[0].to_owned(),
                            type_owner: Some(owner.name().to_owned()),
                            trait_name: Some("From".to_owned()),
                            record: None,
                        });
                }
            }
        }
        Self {
            srcs,
            reach,
            callables,
            fields,
            deref_types,
        }
    }

    fn src(&self, package: &str) -> &Src {
        self.srcs
            .iter()
            .find(|src| src.package == package)
            .expect("a product package")
    }

    /// The key a callable is named by in the tables: an item's, or a generated one's.
    fn key(&self, callable: &Callable) -> String {
        let src = &self.srcs[callable.src];
        match callable.record {
            Some(record) => key_of(src, record),
            None => format!(
                "{} {}::{}::from (generated)",
                src.package,
                callable.module,
                callable.type_owner.as_deref().unwrap_or_default()
            ),
        }
    }

    /// The one first-party type a written type spells. Only leading references are peeled; the
    /// rest must be one path with no arguments or other type syntax, and that path's final name
    /// must identify exactly one reachable first-party type.
    fn written_type(&self, from: usize, src: &Src, toks: &[Tok]) -> BTreeSet<String> {
        let mut at = 0;
        while src.is(toks.get(at), "&") {
            at += 1;
            if toks.get(at).is_some_and(|tok| tok.kind == Kind::Lifetime) {
                at += 1;
            }
            if src.is(toks.get(at), "mut") {
                at += 1;
            }
        }
        let path = &toks[at..];
        if path.is_empty()
            || path.iter().enumerate().any(|(at, tok)| {
                if at % 2 == 0 {
                    tok.kind != Kind::Ident
                } else {
                    !src.is(Some(tok), "::")
                }
            })
            || path.len().is_multiple_of(2)
        {
            return BTreeSet::new();
        }
        let name = src.text(*path.last().expect("a nonempty path"));
        if self.reachable_type_locations(from, name).len() == 1 {
            BTreeSet::from([name.to_owned()])
        } else {
            BTreeSet::new()
        }
    }

    fn reachable_type_locations(&self, from: usize, name: &str) -> BTreeSet<(usize, String)> {
        self.reach[from]
            .iter()
            .flat_map(|at| {
                self.srcs[*at]
                    .index
                    .items()
                    .iter()
                    .filter(|record| {
                        record.kind().is_type()
                            && record.name() == name
                            && self.srcs[*at].product_item(record)
                    })
                    .map(|record| (*at, record.module_paths()[0].to_owned()))
            })
            .collect()
    }

    fn receiver_type_must_fallback(
        &self,
        from: usize,
        name: &str,
        types: &BTreeSet<String>,
    ) -> bool {
        if types.iter().any(|ty| self.deref_types.contains(ty)) {
            return true;
        }
        self.callables
            .get(name)
            .into_iter()
            .flatten()
            .filter(|callable| {
                self.reach[from].contains(&callable.src)
                    && callable
                        .type_owner
                        .as_ref()
                        .is_some_and(|owner| types.contains(owner))
            })
            .filter_map(|callable| callable.trait_name.as_deref())
            .any(|trait_name| {
                let bare = trait_name
                    .split('<')
                    .next()
                    .unwrap_or(trait_name)
                    .rsplit("::")
                    .next()
                    .unwrap_or(trait_name)
                    .trim();
                self.callables.values().flatten().any(|candidate| {
                    self.reach[from].contains(&candidate.src)
                        && candidate.type_owner.is_none()
                        && candidate.trait_name.as_deref().is_some_and(|name| {
                            name.split('<')
                                .next()
                                .unwrap_or(name)
                                .rsplit("::")
                                .next()
                                .unwrap_or(name)
                                .trim()
                                == bare
                        })
                })
            })
    }
}

/// One call, or one macro invocation, found in a body.
#[derive(Clone, Debug)]
struct Site {
    at: usize,
    name: &'static str,
    form: Form,
}

#[derive(Clone, Debug)]
enum Form {
    /// `receiver.name(…)`: the receiver as a chain of names, when it is one.
    Method(Option<Vec<&'static str>>),
    /// `a::b::name(…)`: the qualifiers.
    Path(Vec<&'static str>),
    /// `name(…)`.
    Bare,
    /// `name!(…)`.
    Macro,
    /// A function handed by value to the admission as its work: `admitted::<…>(name)`.
    Value,
}

/// A function's body, as the resolver reads it: its tokens, and what its parameters are.
struct Body<'w> {
    world: &'w World,
    src: usize,
    record: &'static ItemRecord,
    params: HashMap<&'static str, Vec<Tok>>,
    /// Simple locals whose current type is stated by one unshadowed, unreassigned binding.
    locals: HashMap<&'static str, (usize, BTreeSet<String>)>,
    toks: Vec<Tok>,
}

impl<'w> Body<'w> {
    fn new(world: &'w World, src: usize, record: &'static ItemRecord) -> Self {
        let s = &world.srcs[src];
        let declaration = s.lex(record.declaration().start(), record.declaration().end());
        let mut params = HashMap::new();
        let open = declaration
            .iter()
            .position(|t| s.is(Some(t), "fn"))
            .and_then(|at| {
                declaration[at..]
                    .iter()
                    .position(|t| s.is(Some(t), "("))
                    .map(|open| open + at)
            });
        if let Some(open) = open
            && let Some(close) = closing(s, &declaration, open)
        {
            for param in split_commas(s, &declaration[open + 1..close]) {
                let Some(colon) = param.iter().position(|t| s.is(Some(t), ":")) else {
                    continue;
                };
                for name in pattern_names(s, &param[..colon]) {
                    params.insert(name, param[colon + 1..].to_vec());
                }
            }
        }
        let toks = record
            .body()
            .map_or_else(Vec::new, |body| s.lex(body.start(), body.end()));
        let locals = local_types(world, src, record, &toks, &params);
        Self {
            world,
            src,
            record,
            params,
            locals,
            toks,
        }
    }

    fn s(&self) -> &Src {
        &self.world.srcs[self.src]
    }

    /// Every call and macro invocation in the body, in the order they are written.
    fn sites(&self) -> Vec<Site> {
        sites_of(self.s(), &self.toks)
    }

    fn own_methods(&self, all: &[Callable]) -> Vec<Callable> {
        let own = self
            .record
            .type_owner()
            .map(|owner| BTreeSet::from([owner.to_owned()]))
            .unwrap_or_default();
        let methods = methods_of(all, &own);
        let module = self.record.module_paths()[0];
        let here: Vec<Callable> = methods
            .iter()
            .filter(|c| c.src == self.src && c.module == module)
            .cloned()
            .collect();
        if here.is_empty() { methods } else { here }
    }

    fn self_field_type(&self, field: &str) -> BTreeSet<String> {
        let Some(owner) = self.record.type_owner() else {
            return BTreeSet::new();
        };
        let module = self.record.module_paths()[0];
        let mut types = BTreeSet::new();
        for (at, record) in self
            .world
            .fields
            .get(&(owner.to_owned(), field.to_owned()))
            .into_iter()
            .flatten()
            .filter(|(at, record)| *at == self.src && record.module_paths()[0] == module)
        {
            let src = &self.world.srcs[*at];
            let toks = src.lex(record.whole().start(), record.whole().end());
            if let Some(colon) = toks.iter().position(|tok| src.is(Some(tok), ":")) {
                types.extend(self.world.written_type(self.src, src, &toks[colon + 1..]));
            }
        }
        types
    }

    fn receiver_types(&self, site: &Site) -> Option<BTreeSet<String>> {
        let Form::Method(Some(chain)) = &site.form else {
            return None;
        };
        let types = match chain.as_slice() {
            ["self", field] => self.self_field_type(field),
            [local] => self
                .locals
                .get(local)
                .filter(|(bound, _)| *bound < site.at)
                .map(|(_, types)| types.clone())
                .unwrap_or_default(),
            _ => BTreeSet::new(),
        };
        if types.is_empty()
            || self
                .world
                .receiver_type_must_fallback(self.src, site.name, &types)
        {
            None
        } else {
            Some(types)
        }
    }

    fn receiver_is_typed(&self, site: &Site) -> bool {
        match &site.form {
            Form::Method(_) => self.receiver_types(site).is_some(),
            _ => true,
        }
    }

    /// The first-party items a call can be, by what the source states. A receiver type exists only
    /// for `self.field` whose declaration is a reference or one unambiguous first-party path, and
    /// for `let name: Type = …` with the same type restriction when `name` has exactly one binding
    /// in the whole function and is never assigned. Constructor and return expressions are never
    /// typed. A same-name type ambiguity, trait-provided method, or `Deref` receiver is untyped.
    /// Every narrowed lookup goes through [`nonempty_or`], so an empty typed answer always returns
    /// the name-matched answer.
    fn resolve(&self, site: &Site) -> Vec<Callable> {
        let world = self.world;
        let reach = &world.reach[self.src];
        let named = |name: &str| -> Vec<Callable> {
            world
                .callables
                .get(name)
                .into_iter()
                .flatten()
                .filter(|c| reach.contains(&c.src))
                .cloned()
                .collect()
        };
        let all = named(site.name);
        let free = |filter: &dyn Fn(&Callable) -> bool| -> Vec<Callable> {
            all.iter()
                .filter(|c| c.type_owner.is_none() && c.trait_name.is_none() && filter(c))
                .cloned()
                .collect()
        };
        let any_method = || -> Vec<Callable> {
            all.iter()
                .filter(|c| c.type_owner.is_some())
                .cloned()
                .collect()
        };
        let (fallback, preferred) = match &site.form {
            Form::Macro => (Vec::new(), Vec::new()),
            Form::Method(_) if site.name == "into" => {
                let from: Vec<Callable> = named("from")
                    .into_iter()
                    .filter(|c| {
                        c.trait_name
                            .as_deref()
                            .is_some_and(|t| t == "From" || t.starts_with("From<"))
                    })
                    .collect();
                (from.clone(), from)
            }
            Form::Method(Some(chain)) if chain.as_slice() == ["self"] => {
                let preferred = self
                    .record
                    .type_owner()
                    .filter(|owner| !world.deref_types.contains(*owner))
                    .map_or_else(Vec::new, |_| self.own_methods(&all));
                (any_method(), preferred)
            }
            Form::Method(Some(_)) => {
                let preferred = self
                    .receiver_types(site)
                    .map_or_else(Vec::new, |types| methods_of(&all, &types));
                (any_method(), preferred)
            }
            Form::Method(None) => (any_method(), any_method()),
            Form::Path(quals) => match quals.last().copied().unwrap_or_default() {
                "Self" => (any_method(), self.own_methods(&all)),
                "crate" | "self" | "super" => {
                    let preferred = free(&|c: &Callable| c.src == self.src);
                    (free(&|_| true), preferred)
                }
                qualifier if qualifier.starts_with(|c: char| c.is_ascii_uppercase()) => (
                    any_method(),
                    methods_of(&all, &BTreeSet::from([qualifier.to_owned()])),
                ),
                module => {
                    let preferred =
                        free(&|c: &Callable| c.module.rsplit("::").next() == Some(module));
                    (free(&|_| true), preferred)
                }
            },
            Form::Bare | Form::Value => {
                if self.params.contains_key(site.name) {
                    (Vec::new(), Vec::new())
                } else {
                    let module = self.record.module_paths()[0];
                    let here = free(&|c: &Callable| c.src == self.src && c.module == module);
                    let package = free(&|c: &Callable| c.src == self.src);
                    let preferred = if !here.is_empty() { here } else { package };
                    (free(&|_| true), preferred)
                }
            }
        };
        nonempty_or(fallback, preferred)
    }
}

fn nonempty_or(fallback: Vec<Callable>, preferred: Vec<Callable>) -> Vec<Callable> {
    if preferred.is_empty() {
        fallback
    } else {
        preferred
    }
}

/// The end of a `let` statement, respecting delimiters inside its initializer.
fn let_end(s: &Src, toks: &[Tok], start: usize) -> usize {
    let mut depth = 0usize;
    for (at, tok) in toks.iter().enumerate().skip(start) {
        match s.text(*tok) {
            "(" | "[" | "{" => depth += 1,
            ")" | "]" | "}" if depth > 0 => depth -= 1,
            ";" if depth == 0 => return at,
            _ => {}
        }
    }
    toks.len()
}

fn top_level_token(s: &Src, toks: &[Tok], wanted: &str) -> Option<usize> {
    let mut depth = 0usize;
    for (at, tok) in toks.iter().enumerate() {
        match s.text(*tok) {
            "(" | "[" | "{" => depth += 1,
            ")" | "]" | "}" if depth > 0 => depth -= 1,
            text if depth == 0 && text == wanted => return Some(at),
            _ => {}
        }
    }
    None
}

fn receiver_pattern_names(src: &Src, toks: &[Tok]) -> BTreeSet<&'static str> {
    toks.iter()
        .filter(|tok| tok.kind == Kind::Ident)
        .map(|tok| src.text(*tok))
        .filter(|name| {
            ![
                "let", "mut", "ref", "Some", "Ok", "Err", "None", "self", "Self",
            ]
            .contains(name)
                && !name.starts_with(|c: char| c.is_ascii_uppercase())
        })
        .collect()
}

/// How often `name` is introduced by any binding form this lexical guard can encounter. A
/// conservative extra count only disables typing, which is the required direction when a pattern
/// cannot be decided mechanically.
fn binding_count(src: &Src, toks: &[Tok], params: &HashMap<&str, Vec<Tok>>, name: &str) -> usize {
    let mut count = usize::from(params.contains_key(name));
    for (at, tok) in toks.iter().enumerate() {
        if src.is(Some(tok), "let") {
            let end = let_end(src, toks, at + 1);
            let statement = &toks[at + 1..end];
            let pattern_end = top_level_token(src, statement, "=").unwrap_or(statement.len());
            count +=
                usize::from(receiver_pattern_names(src, &statement[..pattern_end]).contains(name));
        }
        if src.is(Some(tok), "for") {
            let rest = &toks[at + 1..];
            if let Some(end) = top_level_token(src, rest, "in") {
                count += usize::from(receiver_pattern_names(src, &rest[..end]).contains(name));
            }
        }
        if src.is(Some(tok), "match") {
            let open = depth_zero(src, toks, at + 1, &["{"]);
            let Some(close) = (open < toks.len())
                .then(|| closing(src, toks, open))
                .flatten()
            else {
                continue;
            };
            let arms = &toks[open + 1..close];
            let mut arm = 0;
            while arm < arms.len() {
                let arrow = depth_zero(src, arms, arm, &["=>"]);
                if arrow >= arms.len() {
                    break;
                }
                let guard = arms[arm..arrow]
                    .iter()
                    .position(|tok| src.is(Some(tok), "if"))
                    .map_or(arrow, |guard| arm + guard);
                count += usize::from(receiver_pattern_names(src, &arms[arm..guard]).contains(name));
                let body = arrow + 1;
                arm = if src.is(arms.get(body), "{") {
                    closing(src, arms, body).map_or(arms.len(), |close| close + 1)
                } else {
                    depth_zero(src, arms, body, &[","])
                };
                if src.is(arms.get(arm), ",") {
                    arm += 1;
                }
            }
        }
    }
    let mut at = 0;
    while at < toks.len() {
        if src.is(toks.get(at), "|")
            && let Some(close) = toks[at + 1..]
                .iter()
                .position(|tok| src.is(Some(tok), "|"))
                .map(|close| close + at + 1)
        {
            count += usize::from(receiver_pattern_names(src, &toks[at + 1..close]).contains(name));
            at = close + 1;
        } else {
            at += 1;
        }
    }
    count
}

fn assigned(src: &Src, toks: &[Tok], name: &str, after: usize) -> bool {
    toks.iter().enumerate().any(|(at, tok)| {
        if tok.start <= after || !src.is(Some(tok), "=") {
            return false;
        }
        let start = toks[..at]
            .iter()
            .rposition(|candidate| {
                [";", "{", "}"]
                    .iter()
                    .any(|stop| src.is(Some(candidate), stop))
            })
            .map_or(0, |start| start + 1);
        let target = &toks[start..at];
        !target
            .iter()
            .any(|candidate| src.is(Some(candidate), "let"))
            && target
                .iter()
                .any(|candidate| candidate.kind == Kind::Ident && src.text(*candidate) == name)
    })
}

/// Locals whose receiver type is stated by exactly `let name: Type = …`, where the written type
/// is a reference or one unambiguous first-party path, the name has exactly one binding in the
/// whole function, and it is never assigned. Initializers never contribute a type.
fn local_types(
    world: &World,
    src: usize,
    _record: &ItemRecord,
    toks: &[Tok],
    params: &HashMap<&str, Vec<Tok>>,
) -> HashMap<&'static str, (usize, BTreeSet<String>)> {
    let s = &world.srcs[src];
    let mut found = HashMap::new();
    for (at, tok) in toks.iter().enumerate() {
        if !s.is(Some(tok), "let") {
            continue;
        }
        let end = let_end(s, toks, at + 1);
        let statement = &toks[at + 1..end];
        let Some(equal) = top_level_token(s, statement, "=") else {
            continue;
        };
        let pattern = &statement[..equal];
        let Some(colon) = top_level_token(s, pattern, ":") else {
            continue;
        };
        let binding: Vec<&Tok> = pattern[..colon]
            .iter()
            .filter(|tok| !s.is(Some(tok), "mut"))
            .collect();
        let [name] = binding.as_slice() else {
            continue;
        };
        if name.kind != Kind::Ident {
            continue;
        }
        let name = s.text(**name);
        let types = world.written_type(src, s, &pattern[colon + 1..]);
        if types.is_empty() {
            continue;
        }
        let bound = toks.get(end).map_or(tok.end, |end| end.start);
        if binding_count(s, toks, params, name) == 1 && !assigned(s, toks, name, bound) {
            found.insert(name, (bound, types));
        }
    }
    found
}

fn methods_of(all: &[Callable], types: &BTreeSet<String>) -> Vec<Callable> {
    all.iter()
        .filter(|c| c.type_owner.as_ref().is_some_and(|t| types.contains(t)))
        .cloned()
        .collect()
}

/// The calls and macro invocations in a run of tokens, in order.
fn sites_of(s: &Src, toks: &[Tok]) -> Vec<Site> {
    let mut out = Vec::new();
    for (at, tok) in toks.iter().enumerate() {
        if tok.kind != Kind::Ident {
            continue;
        }
        let name = s.text(*tok);
        // Past a turbofish: `name::<…>(`.
        let mut next = at + 1;
        if s.is(toks.get(next), "::") && s.is(toks.get(next + 1), "<") {
            let mut depth = 0usize;
            for (inner, t) in toks.iter().enumerate().skip(next + 1) {
                if t.kind != Kind::Punct {
                    continue;
                }
                match s.text(*t) {
                    "<" => depth += 1,
                    ">" => {
                        depth -= 1;
                        if depth == 0 {
                            next = inner + 1;
                            break;
                        }
                    }
                    _ => {}
                }
            }
        }
        if s.is(toks.get(next), "!")
            && ["(", "[", "{"]
                .iter()
                .any(|open| s.is(toks.get(next + 1), open))
        {
            out.push(Site {
                at: tok.start,
                name,
                form: Form::Macro,
            });
            continue;
        }
        if !s.is(toks.get(next), "(") || KEYWORDS.contains(&name) {
            continue;
        }
        let previous = at.checked_sub(1).map(|p| toks[p]);
        let form = if s.is(previous.as_ref(), ".") {
            Form::Method(receiver(s, toks, at - 1))
        } else if s.is(previous.as_ref(), "::") {
            let mut quals = Vec::new();
            let mut colons = at - 1;
            while s.is(toks.get(colons), "::") {
                match colons.checked_sub(1).map(|p| (p, toks[p])) {
                    Some((before, named)) if named.kind == Kind::Ident => {
                        quals.push(s.text(named));
                        let Some(further) = before.checked_sub(1) else {
                            break;
                        };
                        colons = further;
                    }
                    _ => {
                        quals.push("<qualified>");
                        break;
                    }
                }
            }
            quals.reverse();
            Form::Path(quals)
        } else if s.is(previous.as_ref(), "fn") {
            continue;
        } else {
            Form::Bare
        };
        out.push(Site {
            at: tok.start,
            name,
            form,
        });
        // The admission's work, handed over by value: `admitted::<…>(flush)`.
        if name == "admitted"
            && toks.get(next + 1).is_some_and(|t| t.kind == Kind::Ident)
            && s.is(toks.get(next + 2), ")")
        {
            out.push(Site {
                at: toks[next + 1].start,
                name: s.text(toks[next + 1]),
                form: Form::Value,
            });
        }
    }
    out
}

/// The receiver of the method call whose dot is `toks[dot]`, read backwards as `a.b.c`, when it
/// is a plain chain of names.
fn receiver(s: &Src, toks: &[Tok], dot: usize) -> Option<Vec<&'static str>> {
    let mut chain = Vec::new();
    let mut dot = dot;
    loop {
        let named = toks[dot.checked_sub(1)?];
        if named.kind != Kind::Ident {
            return None;
        }
        chain.push(s.text(named));
        match (dot - 1).checked_sub(1).map(|p| toks[p]) {
            Some(before) if s.is(Some(&before), ".") => dot -= 2,
            Some(before) if [")", "]", "?", "::"].iter().any(|p| s.is(Some(&before), p)) => {
                return None;
            }
            _ => break,
        }
    }
    chain.reverse();
    Some(chain)
}

